func TranslateDormitory(roomNo string) string {
	if len(roomNo) < 3 {
		return "未知宿舍"
	}
	buildingCode := roomNo[:3]
	if name, ok := DormitoryMap[buildingCode]; ok {
		return name
	}
	return "未知宿舍(" + buildingCode + ")"
}
